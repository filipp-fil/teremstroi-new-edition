export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

/** Популярные проекты для главной */
export const featuredProjects = projects.filter((p) => p.featured);

/** Слайды hero-баннера на главной */
export const heroProjects = projects.filter((p) => p.hero);

export function getSimilarProjects(project: Project, count = 3): Project[] {
  return projects.filter((p) => p.type === project.type && p.slug !== project.slug).slice(0, count);
}

